"""Bank soal SQUARE ADVENTURE (sumber kebenaran untuk seed database).

Setiap soal memiliki:
- code       : kode unik soal
- type       : mcq | tf | number | sequence | grid_choice
- prompt     : pertanyaan
- visual     : ilustrasi opsional (grid, deret grid, tabel, persegi panjang)
- options    : pilihan jawaban (mcq: teks, grid_choice: {rows, cols})
- answer     : kunci jawaban (TIDAK PERNAH dikirim ke siswa sebelum dinilai)
- hint       : petunjuk singkat ketika jawaban salah
- explanation: pembahasan langkah demi langkah
- skill      : aspek literasi matematis yang dilatih
- ask_reason : siswa diminta menuliskan alasan/strategi (tidak dinilai otomatis)

Aspek literasi (skill):
  identifikasi  - mengidentifikasi informasi matematika
  hubungan      - memahami hubungan susunan persegi dan bilangan
  strategi      - menentukan strategi penyelesaian
  konsep        - menggunakan konsep dan rumus
  tafsir        - menafsirkan hasil perhitungan
  alasan        - menjelaskan alasan jawaban
"""

from __future__ import annotations


def _q(code, qtype, prompt, answer, hint, explanation, *, skill="konsep",
       visual=None, options=None, ask_reason=False):
    return {
        "code": code,
        "type": qtype,
        "prompt": prompt,
        "visual": visual,
        "options": options,
        "answer": answer,
        "hint": hint,
        "explanation": explanation,
        "skill": skill,
        "ask_reason": ask_reason,
    }


def grid(n):
    return {"kind": "grid", "rows": n, "cols": n}


def rect(rows, cols):
    return {"rows": rows, "cols": cols}


